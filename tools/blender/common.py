"""Shared helpers for the procedural Blender asset pipeline.

Every model and environment in this project is generated by a Blender Python
script in this folder. Run them through Blender (see build_all.sh); never
hand-export from other tools.

Conventions (Blender is Z-up, metres; glTF export converts to Y-up):
  * Characters / mechs face -Y in Blender (= +Z "model front" in glTF).
  * Objects named "*_collider" are invisible box colliders for physics
    (extras: {"collider": "box"}). Hide them and build shapes from them.
  * Environment objects carry extras {"collision": "box" | "convex" | "mesh"}
    when the engine should generate static collision for them.
  * Empties named "socket_*" are attachment points; "joint_*" are pivots the
    engine can rotate; other empties (spawns, interactables) carry extras.
"""
import bpy, bmesh, math, os, random
from mathutils import Vector, Matrix, Euler, noise

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
MODELS = os.path.join(ROOT, "assets", "models")
SOURCE = os.path.join(ROOT, "assets", "source")
PREVIEWS = os.path.join(ROOT, "docs", "previews")
PI = math.pi

_MATS, _WM, _COLL = {}, {}, [None]


def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    _MATS.clear(); _WM.clear(); _COLL[0] = None
    bpy.context.scene.unit_settings.system = 'METRIC'


def use_collection(name):
    c = bpy.data.collections.get(name) or bpy.data.collections.new(name)
    if c.name not in bpy.context.scene.collection.children:
        bpy.context.scene.collection.children.link(c)
    _COLL[0] = c
    return c


def hexc(h):
    h = h.lstrip("#"); out = []
    for i in (0, 2, 4):
        c = int(h[i:i + 2], 16) / 255
        out.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return tuple(out)


def mat(name, color="#808080", metal=0.0, rough=0.6, emit=0.0, alpha=1.0):
    """Flat stylized PBR material (cached by name)."""
    if name in _MATS:
        return _MATS[name]
    m = bpy.data.materials.new(name); m.use_nodes = True
    b = m.node_tree.nodes["Principled BSDF"]
    col = (*hexc(color), 1.0)
    b.inputs["Base Color"].default_value = col
    b.inputs["Metallic"].default_value = metal
    b.inputs["Roughness"].default_value = rough
    if emit:
        b.inputs["Emission Color"].default_value = col
        b.inputs["Emission Strength"].default_value = emit
    if alpha < 1.0:
        b.inputs["Alpha"].default_value = alpha
        m.blend_method = 'BLEND'
    m.diffuse_color = (*hexc(color), alpha)
    _MATS[name] = m
    return m


# ---------------------------------------------------------------- objects
def _link(ob, loc, rot, parent, props):
    (_COLL[0] or bpy.context.scene.collection).objects.link(ob)
    wm = Matrix.LocRotScale(Vector(loc), Euler(rot), None)
    _WM[ob.name] = wm
    if parent is not None:
        ob.parent = parent
        ob.matrix_basis = _WM[parent.name].inverted() @ wm
    else:
        ob.matrix_basis = wm
    for k, v in (props or {}).items():
        ob[k] = v
    return ob


def _mesh(name, bm, m, loc, rot, parent, bevel, minsize, props):
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    if m:
        me.materials.append(m)
    ob = bpy.data.objects.new(name, me)
    if bevel > 0:
        md = ob.modifiers.new("Bevel", 'BEVEL')
        md.width = min(bevel, minsize * 0.2); md.segments = 1; md.limit_method = 'ANGLE'
    return _link(ob, loc, rot, parent, props)


def box(name, size, loc=(0, 0, 0), m=None, parent=None, rot=(0, 0, 0), bevel=0.03, taper=None, props=None):
    """World-space box. taper=(sx, sy) scales the +Z face for chunky shapes."""
    bm = bmesh.new(); bmesh.ops.create_cube(bm, size=1.0)
    for v in bm.verts:
        v.co.x *= size[0]; v.co.y *= size[1]; v.co.z *= size[2]
        if taper and v.co.z > 0:
            v.co.x *= taper[0]; v.co.y *= taper[1]
    return _mesh(name, bm, m, loc, rot, parent, bevel, min(size), props)


def cyl(name, r, depth, loc=(0, 0, 0), m=None, parent=None, rot=(0, 0, 0), segs=12, r2=None, bevel=0.0, props=None):
    bm = bmesh.new()
    bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=segs,
                          radius1=r, radius2=r if r2 is None else r2, depth=depth)
    return _mesh(name, bm, m, loc, rot, parent, bevel, min(r, depth), props)


def multi_box(name, parts, m=None, parent=None, props=None, bevel=0.0):
    """Many boxes merged into one mesh. parts: [(size, center[, rot])] in world space."""
    bm = bmesh.new()
    for p in parts:
        size, c = p[0], p[1]
        R = Euler(p[2]).to_matrix().to_4x4() if len(p) > 2 else Matrix.Identity(4)
        bmesh.ops.create_cube(bm, size=1.0, matrix=Matrix.Translation(c) @ R @ Matrix.Diagonal((*size, 1)))
    return _mesh(name, bm, m, (0, 0, 0), (0, 0, 0), parent, bevel, 0.5, props)


def multi_cyl(name, parts, m=None, parent=None, props=None, segs=12):
    """parts: [(radius, depth, center[, rot[, radius2]])] merged into one mesh."""
    bm = bmesh.new()
    for p in parts:
        r, d, c = p[0], p[1], p[2]
        R = Euler(p[3]).to_matrix().to_4x4() if len(p) > 3 else Matrix.Identity(4)
        r2 = p[4] if len(p) > 4 else r
        bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=segs, radius1=r,
                              radius2=r2, depth=d, matrix=Matrix.Translation(c) @ R)
    return _mesh(name, bm, m, (0, 0, 0), (0, 0, 0), parent, 0, 0.5, props)


def seg_xf(a, b):
    """Centre, euler and length of a box spanning point a -> b along its local Z."""
    a, b = Vector(a), Vector(b); d = b - a
    rot = Vector((0, 0, 1)).rotation_difference(d.normalized()).to_euler()
    return tuple((a + b) / 2), tuple(rot), d.length


def seg(name, a, b, w, d, m=None, parent=None, bevel=0.04, taper=None, props=None):
    c, r, L = seg_xf(a, b)
    return box(name, (w, d, L), c, m, parent, r, bevel, taper, props)


def empty(name, loc=(0, 0, 0), parent=None, rot=(0, 0, 0), props=None, size=0.25):
    ob = bpy.data.objects.new(name, None)
    ob.empty_display_type = 'ARROWS'; ob.empty_display_size = size
    return _link(ob, loc, rot, parent, props)


def collider(name, size, loc, parent, rot=(0, 0, 0)):
    ob = box(name, size, loc, None, parent, rot, bevel=0, props={"collider": "box"})
    ob.display_type = 'WIRE'; ob.hide_render = True
    return ob


def text(name, body, size, loc, rot=(PI / 2, 0, 0), m=None, parent=None, extrude=0.04, props=None):
    """Extruded text converted to a mesh. Default rot faces -Y."""
    cu = bpy.data.curves.new(name, 'FONT')
    cu.body = body; cu.size = size; cu.extrude = extrude
    cu.align_x = 'CENTER'; cu.align_y = 'CENTER'
    tmp = bpy.data.objects.new(name + "_tmp", cu)
    bpy.context.scene.collection.objects.link(tmp)
    dg = bpy.context.evaluated_depsgraph_get()
    me = bpy.data.meshes.new_from_object(tmp.evaluated_get(dg))
    bpy.data.objects.remove(tmp); bpy.data.curves.remove(cu)
    me.materials.clear()
    if m:
        me.materials.append(m)
    return _link(bpy.data.objects.new(name, me), loc, rot, parent, props)


def point_light(name, loc, energy, color="#FFF1D6", radius=0.25, parent=None):
    ld = bpy.data.lights.new(name, 'POINT')
    ld.energy = energy; ld.color = hexc(color); ld.shadow_soft_size = radius
    return _link(bpy.data.objects.new(name, ld), loc, (0, 0, 0), parent, None)


def spot_light(name, loc, target, energy, angle=0.7, color="#FFF4E0"):
    ld = bpy.data.lights.new(name, 'SPOT')
    ld.energy = energy; ld.color = hexc(color); ld.spot_size = angle; ld.spot_blend = 0.4
    rot = (Vector(target) - Vector(loc)).to_track_quat('-Z', 'Y').to_euler()
    return _link(bpy.data.objects.new(name, ld), loc, tuple(rot), None, None)


def hazard_strip(name, a, b, width, seg_len=0.6, z=0.012, h=0.02, parent=None):
    a, b = Vector(a), Vector(b); d = b - a
    n = max(2, int(d.length / seg_len)); ang = math.atan2(d.y, d.x)
    y, k = [], []
    for i in range(n):
        c = a + d * ((i + 0.5) / n)
        (y if i % 2 == 0 else k).append(((d.length / n, width, h), (c.x, c.y, z), (0, 0, ang)))
    multi_box(name + "_yellow", y, mat("hazard_yellow", "#F2C230", 0, 0.5), parent)
    multi_box(name + "_black", k, mat("hazard_black", "#1B1C1E", 0, 0.6), parent)


def drum(name, loc, color="#2F5D8C", parent=None, props=None):
    x, y, z = loc
    body = cyl(name, 0.3, 0.9, (x, y, z + 0.45), mat("drum_" + color, color, 0.4, 0.5), parent, segs=14,
               props=props or {"collision": "box"})
    multi_cyl(name + "_bands", [(0.315, 0.05, (x, y, z + 0.25)), (0.315, 0.05, (x, y, z + 0.65)),
                                (0.31, 0.03, (x, y, z + 0.9))],
              mat("drum_band", "#2A2C2F", 0.6, 0.5), body, segs=14)
    return body


def crate(name, loc, s=1.0, rotz=0.0, parent=None, props=None):
    x, y, z = loc
    c = box(name, (s, s, s), (x, y, z + s / 2), mat("crate_wood", "#A87A4A", 0, 0.8), parent, (0, 0, rotz),
            bevel=0.04, props=props or {"collision": "box"})
    e = s * 1.02
    multi_box(name + "_bands", [((e, e, 0.08 * s), (x, y, z + s * 0.2), (0, 0, rotz)),
                                ((e, e, 0.08 * s), (x, y, z + s * 0.8), (0, 0, rotz))],
              mat("crate_band", "#3A3F47", 0.7, 0.45), c)
    return c


def hierarchy(root):
    return [root] + list(root.children_recursive)


# ---------------------------------------------------------------- output
def export_glb(path, objs=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    for o in bpy.context.scene.objects:
        o.select_set(False)
    for o in objs or []:
        o.select_set(True)
    bpy.ops.export_scene.gltf(filepath=path, export_format='GLB', use_selection=bool(objs),
                              export_apply=True, export_extras=True, export_yup=True,
                              export_lights=True, export_cameras=False)
    print("EXPORTED", os.path.relpath(path, ROOT))


def save_blend(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=path, compress=True)
    print("SAVED", os.path.relpath(path, ROOT))


def render_preview(name, cam_loc, target, lens=35, sun=3.0, sun_rot=(0.9, 0.2, 0.6), sun_color="#FFF1DE",
                   world="#9DB4C8", world_strength=0.8, ground=None, res=(1280, 720), samples=128):
    if os.environ.get("SKIP_RENDER"):
        return
    sc = bpy.context.scene
    use_collection("_preview")
    cd = bpy.data.cameras.new("PreviewCam"); cd.lens = lens; cd.clip_end = 1000
    rot = (Vector(target) - Vector(cam_loc)).to_track_quat('-Z', 'Y').to_euler()
    sc.camera = _link(bpy.data.objects.new("PreviewCam", cd), cam_loc, tuple(rot), None, None)
    if sun:
        ld = bpy.data.lights.new("PreviewSun", 'SUN'); ld.energy = sun; ld.color = hexc(sun_color); ld.angle = 0.05
        _link(bpy.data.objects.new("PreviewSun", ld), (0, 0, 50), sun_rot, None, None)
    if ground:
        box("PreviewGround", (400, 400, 0.1), (0, 0, -0.05), mat("preview_ground", ground, 0, 0.9), bevel=0)
    w = bpy.data.worlds.new("World"); w.use_nodes = True
    bg = w.node_tree.nodes["Background"]
    bg.inputs[0].default_value = (*hexc(world), 1); bg.inputs[1].default_value = world_strength
    sc.world = w
    sc.render.engine = 'CYCLES'; sc.cycles.device = 'CPU'
    sc.cycles.samples = samples; sc.cycles.max_bounces = 6
    sc.cycles.use_denoising = False  # distro Blender ships without OpenImageDenoise
    sc.cycles.use_adaptive_sampling = True
    sc.cycles.sample_clamp_indirect = 2.0  # kill fireflies
    try:
        sc.view_settings.view_transform = 'AgX'; sc.view_settings.look = 'AgX - Punchy'
    except Exception:
        pass
    q = float(os.environ.get("PREVIEW_SCALE", "1"))  # e.g. 0.35 for a quick draft render
    if q < 1:
        res, sc.cycles.samples = (int(res[0] * q), int(res[1] * q)), max(8, int(samples * q))
    sc.render.resolution_x, sc.render.resolution_y = res
    sc.render.resolution_percentage = 100
    sc.render.image_settings.file_format = 'PNG'
    sc.render.filepath = os.path.join(PREVIEWS, name + ".png")
    os.makedirs(PREVIEWS, exist_ok=True)
    bpy.ops.render.render(write_still=True)
    print("RENDERED", os.path.relpath(sc.render.filepath, ROOT))
